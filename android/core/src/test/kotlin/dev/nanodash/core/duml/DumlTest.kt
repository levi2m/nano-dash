package dev.nanodash.core.duml

import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

private fun String.hex(): ByteArray = replace(" ", "").chunked(2).map { it.toInt(16).toByte() }.toByteArray()
private fun ByteArray.hex(): String = joinToString("") { "%02x".format(it) }

class DumlTest {
    // Frame published in Osmosis' MEDIA_PROTOCOL.md (GetWifiSsid).
    @Test
    fun buildMatchesDocumentedExample() {
        val f = Duml.build(0x02, 0x07, 0xA000, 0x40, 0x07, 0x07)
        assertEquals("550d0433020700a04007077472", f.hex())
    }

    // Frames generated by the validated Python spike (tools/ble-spike) with the same inputs: two independent implementations agree.
    @Test
    fun outgoingFramesMatchPythonSpike() {
        assertEquals(
            "553304c202073412400745203030313132323333343435353636373738383939616162626363646465656666046f736d6f0051",
            CameraFrames.pair("00112233445566778899aabbccddeeff", 0x1234).hex(),
        )
        assertEquals("550f04a202f0010040002b010163a0", CameraFrames.keepalive(1).hex())
        assertEquals("550f04a202f0020040002b04003c67", CameraFrames.prePair(2).hex())
        assertEquals("55110492021c030040531000000000b767", CameraFrames.wake(3).hex())
        assertEquals("550e04660201040040020201a454", CameraFrames.recordStart(4).hex())
        assertEquals("550e046602010500400202000641", CameraFrames.recordStop(5).hex())
    }

    // Frames captured from a real Osmo Nano during the M0 spike on 2026-11-02 (camera to phone), CRCs and all.
    @Test
    fun parsesRealCameraFrames() {
        val pairingReply = Duml.parse("55 0f 04 a2 07 02 e4 5c c0 07 45 00 02 40 da".hex())
        assertEquals(Addr.WIFI, pairingReply.sender)
        assertEquals(Addr.APP, pairingReply.receiver)
        assertEquals(CameraReplies.Pairing.APPROVAL_REQUIRED, CameraReplies.pairing(pairingReply))

        val approval = Duml.parse("55 0e 04 66 07 02 02 00 40 07 46 01 ea 6b".hex())
        assertTrue(CameraReplies.isApprovalRequest(approval))
        assertEquals(2, approval.seq)

        val wake = Duml.parse("55 11 04 92 1c 02 e5 5c c0 53 10 01 00 00 00 59 e2".hex())
        assertTrue(CameraReplies.isWakeReply(wake))
        assertContentEquals("01000000".hex(), wake.payload)

        val status = Duml.parse(
            ("55 49 04 93 01 02 aa 0d 00 02 80 01 02 80 00 01 5f ae 01 00 78 14 01 00 00 00 00 00 09 1a 00 00 00 00 00 00 " +
                "00 00 00 00 00 00 00 00 70 00 00 01 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 01 00 00 86 ee").hex(),
        )
        assertEquals(60, status.payload.size)
        assertEquals(false, CameraReplies.isRecording(status))
    }

    @Test
    fun recordingFlagIsBit7OfByte0() {
        val payload = ByteArray(60).also { it[0] = 0x81.toByte() }
        val recording = Duml.parse(Duml.build(Addr.CAMERA, Addr.APP, 1, 0x00, 0x02, 0x80, payload))
        assertEquals(true, CameraReplies.isRecording(recording))
        val other = Duml.parse(Duml.build(Addr.CAMERA, Addr.APP, 1, 0x00, 0x0D, 0x02, payload))
        assertNull(CameraReplies.isRecording(other))
    }

    @Test
    fun recordReplyCodes() {
        fun reply(code: Int) = Duml.parse(Duml.build(Addr.CAMERA, Addr.APP, 9, 0xC0, 0x02, 0x02, byteArrayOf(code.toByte())))
        assertTrue(CameraReplies.recordAccepted(reply(0x00)))
        assertFalse(CameraReplies.recordAccepted(reply(0xD6)))   // seen while USB was connected
        assertFalse(CameraReplies.recordAccepted(reply(0xDF)))
    }

    @Test
    fun rejectsCorruptFrames() {
        val good = "55 0f 04 a2 07 02 e4 5c c0 07 45 00 02 40 da".hex()
        val badPayload = good.copyOf().also { it[11] = 1 }
        assertFailsWith<DumlException> { Duml.parse(badPayload) }                       // crc16
        val badHeader = good.copyOf().also { it[3] = 0 }
        assertFailsWith<DumlException> { Duml.parse(badHeader) }                        // crc8
        assertFailsWith<DumlException> { Duml.parse(good.copyOf(good.size - 1)) }       // length
        assertFailsWith<DumlException> { Duml.parse(byteArrayOf(0x00, 0x01)) }          // not a frame
    }

    @Test
    fun reassemblerHandlesSplitMergedAndNoise() {
        val a = CameraFrames.keepalive(1)
        val b = CameraFrames.wake(2)
        val r = DumlReassembler()
        // split across three notifications
        assertEquals(0, r.feed(a.copyOfRange(0, 4)).size)
        assertEquals(0, r.feed(a.copyOfRange(4, 9)).size)
        assertContentEquals(a, r.feed(a.copyOfRange(9, a.size)).single())
        // two frames merged into one notification, preceded by noise
        val merged = r.feed(byteArrayOf(0x01, 0x02) + a + b)
        assertEquals(2, merged.size)
        assertContentEquals(a, merged[0])
        assertContentEquals(b, merged[1])
        // a frame that begins at the end of one packet and a bogus 0x55 byte
        assertEquals(0, r.feed(byteArrayOf(0x55, 0x00)).size)
        assertContentEquals(a, r.feed(a).single())
    }

    @Test
    fun buildParseRoundTripWithLargePayload() {
        val payload = ByteArray(300) { it.toByte() }
        val f = Duml.parse(Duml.build(0x02, 0x08, 0xBEEF, 0x40, 0x08, 0x78, payload))
        assertEquals(0xBEEF, f.seq)
        assertContentEquals(payload, f.payload)
    }
}
